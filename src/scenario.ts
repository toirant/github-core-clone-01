export interface ScenarioUser {
  id: number;
  login: string;
  name: string;
  email: string;
}

/** The scenario's 12 users, in order; users[0] is the viewer, users[2] the stranger. */
export function generateUsers(): ScenarioUser[] {
  const rng = Rng.fromLabel('users');
  const used = new Set<string>();
  const users: ScenarioUser[] = [];
  for (let i = 0; i < 12; i += 1) {
    const first = rng.pick(FIRST_NAMES);
    const last = rng.pick(LAST_NAMES);
    const base = `${first}${last}`.replace(/[^a-z0-9-]/g, '');
    let login = base;
    let suffix = 2;
    while (used.has(login)) {
      login = `${base}-${suffix}`;
      suffix += 1;
    }
    used.add(login);
    users.push({ id: 1000 + i, login, name: `${first} ${last}`, email: `${login}@example.invalid` });
  }
  return users;
}

const USERS = generateUsers();

/** The login the shop token names: the scenario's viewer. */
export const VIEWER_LOGIN = USERS[0]?.login ?? 'adaiversen';
/** The scenario's viewer user id. */
export const VIEWER_ID = USERS[0]?.id ?? 1000;
/** The scenario's stranger (a different user, used for ownership checks). */
export const STRANGER_LOGIN = USERS[2]?.login ?? 'olgabauer';
